-- YSCMT Enterprise customer support desk.
create table if not exists public.enterprise_support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_email text not null,
  subject text not null,
  category text not null check (category in ('billing','technical','account','service','other')),
  priority text not null default 'normal' check (priority in ('low','normal','high')),
  status text not null default 'open' check (status in ('open','in_progress','waiting_customer','closed')),
  assigned_to uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint enterprise_support_customer_email_check check (customer_email=lower(customer_email))
);
create index if not exists enterprise_support_tickets_customer_idx
  on public.enterprise_support_tickets(lower(customer_email),updated_at desc);
create index if not exists enterprise_support_tickets_queue_idx
  on public.enterprise_support_tickets(status,priority,updated_at desc);
create table if not exists public.enterprise_support_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.enterprise_support_tickets(id) on delete cascade,
  sender_type text not null check (sender_type in ('customer','admin')),
  sender_name text not null,
  sender_admin_id uuid,
  message text not null check (length(trim(message)) between 2 and 4000),
  created_at timestamptz not null default now()
);
create index if not exists enterprise_support_messages_ticket_idx
  on public.enterprise_support_messages(ticket_id,created_at);
